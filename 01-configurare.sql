-- ATENȚIE: șterge definitiv tabelele public.client și public.formula_client existente.
-- Nu șterge conturile de autentificare din Supabase.
begin;

drop table if exists public.formula_client cascade;
drop table if exists public.client cascade;

create table public.client (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nume text not null,
  formula text not null default ''
);

create index client_user_id_idx on public.client(user_id);
alter table public.client enable row level security;

create policy client_select_own on public.client
  for select to authenticated using (auth.uid() = user_id);
create policy client_insert_own on public.client
  for insert to authenticated with check (auth.uid() = user_id);
create policy client_update_own on public.client
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy client_delete_own on public.client
  for delete to authenticated using (auth.uid() = user_id);

grant select, insert, update, delete on public.client to authenticated;
grant usage, select on sequence public.client_id_seq to authenticated;
commit;
